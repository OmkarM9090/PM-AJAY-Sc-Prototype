    jobs = []
    for i, (title, sector, district, state, qpc, edu, salary, openings, employer) in enumerate(WAGE_JOBS, start=1):
        jobs.append({
            "opportunity_id": f"JOB{i:03d}",
            "type": "job",
            "title": title,
            "sector": sector,
            "district": district,
            "state": state,
            "linked_qp": qpc,
            "min_education": edu,
            "monthly_income_range": salary,
            "openings": openings,
            "employer": employer,
            "source": "Demo dataset modelled on NCS-style listings",
        })
    se = []
    for i, (title, sector, district, state, qpc, inv, tools, income, gia) in enumerate(SELF_EMPLOYMENT, start=1):
        se.append({
            "opportunity_id": f"SE{i:03d}",
            "type": "self-employment",
            "title": title,
            "sector": sector,
            "district": district,
            "state": state,
            "linked_qp": qpc,
            "required_investment_inr": inv,
            "tools_required": tools,
            "monthly_income_range": income,
            "gia_support_head": gia,
            "source": "Demo dataset modelled on PM-AJAY GIA enterprise support norms",
        })
    return jobs + se


